"""
scripts/build_grounded_sft.py
==============================
Build SFT training data for the 'reflect_grounded' condition using a
two-model pipeline:

  Step 1 — Student model generates wrong first attempts on training problems.
  Step 2 — Teacher model generates grounded, forced-quote reflections for
            each wrong attempt (seeing the correct answer as oracle context).
  Step 3 — Assemble (reflection_turn, retry_turn) SFT pairs and write to JSONL.

Key differences from the original reflect_full_retry curriculum:
  • The failed solution is INCLUDED in the reflection prompt (not omitted)
  • The "no digits" constraint is REMOVED — specific values are required
  • Reflections are generated by the teacher model, not a hardcoded constant
  • The forced-quote format (WRONG LINE / WHY WRONG / CORRECT VALUE) requires
    the model to cite a specific line from the failed attempt

Output:
  data/processed/curriculum/reflect_grounded.jsonl  (default)

Usage
-----
  # Generate ~2 000 grounded SFT examples (fast initial test)
  python scripts/build_grounded_sft.py \\
      --student_model Qwen/Qwen3-4B \\
      --teacher_model Qwen/Qwen3-8B \\
      --limit 1000 \\
      --out_jsonl data/processed/curriculum/reflect_grounded.jsonl

  # Larger run for production training
  python scripts/build_grounded_sft.py \\
      --student_model Qwen/Qwen3-4B \\
      --teacher_model Qwen/Qwen3-8B \\
      --limit 5000 \\
      --out_jsonl data/processed/curriculum/reflect_grounded.jsonl

The --limit cap applies to *problems attempted*, not pairs written.
Typically ~60-70% of problems yield a wrong first attempt and a parseable
grounded reflection, so --limit 1000 produces ~600-700 SFT pairs.

Resume / incremental
--------------------
Pass --resume to skip problems whose question already appears in the
output file. Safe to re-run after a partial failure.
"""

